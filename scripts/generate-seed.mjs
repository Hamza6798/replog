// Builds supabase/seed.sql from the local dataset.  Run: npm run seed:generate
import { writeFileSync } from 'node:fs'
import { exercises } from '../src/data/exercises.js'

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const arr = (a) => (a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`)

const rows = exercises.map((e) =>
  `(${[q(e.id), q(e.name), q(e.category), q(e.primaryMuscle), arr(e.secondaryMuscles), q(e.equipment), q(e.difficulty), q(e.type), arr(e.instructions), arr(e.mistakes), e.imageUrl ? q(e.imageUrl) : 'null'].join(', ')})`,
)
const sql = `-- Generated by scripts/generate-seed.mjs. Safe to run more than once.
insert into public.exercises (code, name, category, primary_muscle, secondary_muscles, equipment, difficulty, type, instructions, mistakes, image_url)
values
${rows.join(',\n')}
on conflict (code) do update set
  name = excluded.name, category = excluded.category, primary_muscle = excluded.primary_muscle,
  secondary_muscles = excluded.secondary_muscles, equipment = excluded.equipment,
  difficulty = excluded.difficulty, type = excluded.type,
  instructions = excluded.instructions, mistakes = excluded.mistakes, image_url = excluded.image_url;
`
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`Wrote supabase/seed.sql with ${exercises.length} exercises`)
