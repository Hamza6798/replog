// Downloads demonstration images from the Free Exercise DB (Unlicense / public domain,
// https://github.com/yuhonas/free-exercise-db) into public/exercises and writes
// src/data/exerciseImages.js. Run: npm run images:fetch   (needs internet; Python Pillow optional for resizing)
import { mkdirSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'

const BASE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/'
// REPLOG exercise ID -> Free Exercise DB folder name. Exercises without a fair match are left out on purpose.
const MAP = {
  '0001': 'Barbell_Bench_Press_-_Medium_Grip', '0002': 'Incline_Dumbbell_Press', '0003': 'Dumbbell_Bench_Press', '0004': 'Dumbbell_Flyes',
  '0005': 'Pushups', '0006': 'Cable_Crossover', '0007': 'Leverage_Chest_Press', '0008': 'Decline_Barbell_Bench_Press',
  '0009': 'Pullups', '0010': 'Wide-Grip_Lat_Pulldown', '0011': 'Bent_Over_Barbell_Row', '0012': 'One-Arm_Dumbbell_Row',
  '0013': 'Seated_Cable_Rows', '0014': 'Barbell_Deadlift', '0015': 'T-Bar_Row_with_Handle', '0016': 'Band_Pull_Apart',
  '0017': 'Straight-Arm_Pulldown', '0018': 'Standing_Military_Press', '0019': 'Dumbbell_Shoulder_Press', '0020': 'Side_Lateral_Raise',
  '0021': 'Front_Dumbbell_Raise', '0022': 'Seated_Bent-Over_Rear_Delt_Raise', '0023': 'Arnold_Dumbbell_Press', '0024': 'Cable_Seated_Lateral_Raise',
  '0025': 'Barbell_Curl', '0026': 'Hammer_Curls', '0027': 'Incline_Dumbbell_Curl', '0028': 'Standing_Biceps_Cable_Curl',
  '0029': 'Machine_Preacher_Curls', '0031': 'Triceps_Pushdown', '0032': 'EZ-Bar_Skullcrusher', '0033': 'Dumbbell_One-Arm_Triceps_Extension',
  '0034': 'Close-Grip_Barbell_Bench_Press', '0035': 'Bench_Dips', '0036': 'Tricep_Dumbbell_Kickback', '0037': 'Barbell_Squat',
  '0038': 'Goblet_Squat', '0039': 'Leg_Press', '0040': 'Romanian_Deadlift', '0041': 'Bodyweight_Walking_Lunge',
  '0042': 'Leg_Extensions', '0043': 'Seated_Leg_Curl', '0044': 'Standing_Calf_Raises', '0046': 'Barbell_Hip_Thrust',
  '0047': 'Bodyweight_Squat', '0048': 'Plank', '0049': 'Crunches', '0050': 'Hanging_Leg_Raise',
  '0051': 'Cable_Crunch', '0052': 'Russian_Twist', '0053': 'Ab_Roller', '0054': 'Rope_Jumping',
  '0056': 'Mountain_Climbers', '0057': 'Rowing_Stationary', '0061': 'Clean_and_Press', '0062': 'Kettlebell_Turkish_Get-Up_Squat_style',
  '0063': 'Farmers_Walk',
}

mkdirSync('public/exercises', { recursive: true })
const out = {}
for (const [id, folder] of Object.entries(MAP)) {
  const files = []
  for (const n of [0, 1]) {
    const res = await fetch(`${BASE}${folder}/${n}.jpg`)
    if (!res.ok) { if (n === 0) console.warn(`SKIP ${id} ${folder}: HTTP ${res.status}`); continue }
    const name = `${id}-${n}.jpg`
    writeFileSync(`public/exercises/${name}`, Buffer.from(await res.arrayBuffer()))
    files.push(`/exercises/${name}`)
  }
  if (files.length) out[id] = files
}
// Shrink to 640px wide so pages load fast (skipped if Pillow is missing).
try {
  execFileSync('python3', ['-c', `
import glob
from PIL import Image
for p in glob.glob('public/exercises/*.jpg'):
    im = Image.open(p).convert('RGB')
    if im.width > 640: im = im.resize((640, round(im.height * 640 / im.width)))
    im.save(p, 'JPEG', quality=78, optimize=True)
`])
} catch { console.warn('Resize skipped (Pillow not installed).') }

writeFileSync('src/data/exerciseImages.js',
  `// Generated by scripts/fetch-exercise-images.mjs. Images: Free Exercise DB (Unlicense, public domain).\nexport const exerciseImages = ${JSON.stringify(out, null, 2)}\n`)
console.log(`Saved images for ${Object.keys(out).length} exercises`)
